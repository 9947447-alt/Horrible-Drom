const DEFAULT_PROP_TINT = '#8a6a45';

function buildTheme(id, data) {
  const wall = { ...data.wall };
  const floor = { ...data.floor };
  const window = { ...data.window };
  return {
    id,
    ...data,
    wall,
    floor,
    window,
    propTint: data.propTint || DEFAULT_PROP_TINT,
  };
}

export const ROOM_THEMES = Object.fromEntries(
  Object.entries(THEME_DATA).map(([id, data]) => [id, buildTheme(id, data)])
);

export const THEME_IDS = Object.keys(ROOM_THEMES);

export function getRoomTheme(room) {
  const id = room?.theme;
  return ROOM_THEMES[id] || ROOM_THEMES.wood;
}

